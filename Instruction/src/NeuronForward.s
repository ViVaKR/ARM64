.globl _Nuron_Forward
.p2align 2

// ============================================================
// 미니 뉴런 시뮬레이션 (2개 입력 → 1개 출력)
//
//   출력(output) = (입력0 × 가중치0) + (입력1 × 가중치1)
//   오차(error)  = 정답(target) - 출력(output)
//
// 문서 분식집 얘기 그대로: 입력 = "주문 개수", 가중치 = "가격"
// 다만 이번엔 가격(가중치)이 "아직 학습 안 된 엉터리 값"이라는 게 포인트.
// ============================================================

_Nuron_Forward:

     // ---- 1. 입력값 (실제 데이터, 고정값) ----
    // 예: 떡복기 2개, 김밥 3개 주문 (철수)
    mov w0, #2 // 입력 0
    mov w1, #3 // 입력 1
    ins v0.s[0], w0
    ins v0.s[1], w1 // v0 = [입력0, 입력1] = [2, 3]

    // 2. 가중치 "랜범 초기화"
    // 진짜 랜덤 대신 일부러 엉터리 값을 넣어서 "아직 학습 안됨"을 흉내냄.
    // 진짜 정답 가경은 [3000, 2000] 인데 초기 가중치는 아무렇게나 [10, 10] 으로 시작
    mov w2, #10 // 가중치 0 (엉터리)
    mov w3, #10 // 가중치 1 (엉터리)
    ins v1.s[0], w2
    ins v1.s[1], w3  // v1 = [가중치0, 가중치1] = [10, 10]

    // 3. 순전파(forward) = "곱하고 더하기"
    mul v2.2s, v0.2s, v1.2s // v2 = [입력0x가중치0, 입력1x가중치1] = [20, 30]
    addp v2.2s, v2.2s, v2.2s // v2.s[0] = 20 + 30 = 50 <- 출력본 (output)

    // (lldb) register read -f unit32_t[] v2
    // v2 = {0x00000032 ...} -> 0x32 = 50

    // (lldb) register read -f uint32_t[] v0    // 입력값 [2, 3]
    // (lldb) register read -f uint32_t[] v1    // 초기 가중치(엉터리) [10, 10]
    // (lldb) register read -f uint32_t[] v2    // 순전파 출력 [50]
    // (lldb) register read -f uint32_t[] v4    // 오차 [11950]

    // 4. 오차 계산
    // 정답(target)은 우리가 알고 있음: 철수가 실제로 낸 돈 = 12000원
    // 하지만 지금 가중치가 엉터리라 출력은 50밖에 안 나옴 → 오차가 어마어마함
    mov w4, #12000 // target (정답)
    dup v3.2s, w4 // v3 = [target, target] = [12000, 12000]
    sub v4.2s, v3.2s, v2.2s // v4.s[0] = target - output = 12000 - 50 = 11950

    // (lldb) register read -f uint32_t[] v4
    // v4.s[0] = 11950  ← 이게 "오차(error)". 엄청 크지? 가중치가 아직 엉터리라서 그래.




    // ---- 5. (다음 단계 예고) ----
    // 실제 학습(backpropagation)에서는 이 오차를 보고
    // 가중치를 "오차 방향으로 아주 조금" 수정함:
    //     새가중치 = 기존가중치 + (학습률 × 오차 × 입력)
    // 이걸 수백~수백만 번 반복하면 가중치[10,10] → 점점 → [3000,2000]에 수렴함.
    // (이 부분은 나눗셈/실수 연산이 필요해서 fmul/fdiv 편에서 이어서 다룰 예정)
    ret
