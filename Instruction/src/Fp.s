
.section __TEXT,__text,regular,pure_instructions
.p2align 2

.globl _Fp

// register read d0 d1 d2 d3 d4 d5 d6

_Fp:

    fmov d0, #2.5
    fmov d1, #1.5

    // ====================================================
    // 🎯 1. 상남자의 정석, 스칼라(Scalar) 연산
    // ====================================================

    fadd d2, d0, d1 // 덧셈 d2 = 2.5 + 1.5 = 4.0
    fsub d3, d0, d1 // 뺄셈 d3 = 2.5 - 1.5 = 1.0
    fmul d4, d0, d1 // 곱셈 d4 = 2.5 * 1.5 = 3.75
    fdiv d5, d0, d1 // 나눗셈 d5 = 2.5 / 1.5 = 1.6666...
    fsqrt d6, d2 // 제곱근 d6 = √4.0 = 2.0

    // ====================================================
    // ⚡ 2. M4 AI 파워의 근본, NEON 벡터(SIMD) 연산
    // ====================================================

    ret
