.section __TEXT,__text, regular, pure_instructions
.p2align 2
.globl _FpVector

// ====================================================
// ⚡ 2. M4 AI 파워의 근본, NEON 벡터(SIMD) 연산
// ====================================================
_FpVector:

    // v0, v1 방에 이미 4개의 float 데이터 배열
    // v0.4s = [1.0, 2.0, 3.0, 4.0]
    // v1.4s = [0.5, 0.5, 0.5, 0.5]
    // 🎯 fmov를 사용해 정수 레지스터(w0~w3)에 실수의 '비트'를 그대로 복사합니다!
    mov w0, #0          // 1.0의 2진수 비트(0x3f800000)가 w0에 그대로 탑재됨
    mov w1, #1
    mov w2, #2
    mov w3, #3

    // 🎯 장전된 정수 레지스터를 사용하므로, 이제 'ins' 명령어를 100% 그대로 사용 가능!
    ins v0.s[0], w0        // w0에 들어있는 1.0의 비트가 v0의 0번방에 입주!
    ins v0.s[1], w1        // v0 = [1.0, 2.0] 완성!

    ins v1.s[0], w2        // w2에 들어있는 3.0의 비트가 v1의 0번방에 입주!
    ins v1.s[1], w3        // v1 = [3.0, 4.0] 완성!

;    fmov s0, #1.0
